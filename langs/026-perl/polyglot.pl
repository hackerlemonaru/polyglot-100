use strict;
use warnings;
use feature 'say';
use List::Util qw(sum);

sub fib {
    my ($n) = @_;
    my ($a, $b) = (0, 1);
    for (1 .. $n) {
        ($a, $b) = ($b, $a + $b);
    }
    return $a;
}

my $total = sum(1 .. 10);
say "Hello from Perl!";
say "sum(1..10) = $total";
printf "fib(10)    = %d\n", fib(10);
die "the 55 coincidence failed\n" unless $total == fib(10);
