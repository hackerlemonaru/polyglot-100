import std/strutils

func fib(n: int): int64 =
  var (a, b) = (0'i64, 1'i64)
  for _ in 0 ..< n:
    let t = a + b
    a = b
    b = t
  a

proc main() =
  var sum = 0
  for i in 1 .. 10:
    sum += i
  echo "Hello from Nim!"
  echo "sum(1..10) = ", sum
  echo "fib(10)    = ", fib(10)

when isMainModule:
  main()
