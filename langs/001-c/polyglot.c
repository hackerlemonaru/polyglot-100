#include <stdio.h>

static long fib(int n) {
    long a = 0, b = 1;
    for (int i = 0; i < n; i++) {
        long t = a + b;
        a = b;
        b = t;
    }
    return a;
}

int main(void) {
    long sum = 0;
    for (int i = 1; i <= 10; i++) sum += i;
    printf("Hello from C!\n");
    printf("sum(1..10) = %ld\n", sum);
    printf("fib(10)    = %ld\n", fib(10));
    return 0;
}
