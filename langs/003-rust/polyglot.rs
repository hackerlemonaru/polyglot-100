fn fib(n: u32) -> u64 {
    let (mut a, mut b) = (0u64, 1u64);
    for _ in 0..n {
        let t = a + b;
        a = b;
        b = t;
    }
    a
}

fn main() {
    let sum: u32 = (1..=10).sum();
    println!("Hello from Rust!");
    println!("sum(1..10) = {sum}");
    println!("fib(10)    = {}", fib(10));
    assert_eq!(sum as u64, fib(10), "the 55 coincidence");
}
